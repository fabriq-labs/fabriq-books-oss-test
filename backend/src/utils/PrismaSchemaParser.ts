import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { EntityDefinition, FieldDefinition, RelationshipDefinition } from '../models/ModelRegistry';

export class PrismaSchemaParser {
  private schemaContent: string;

  constructor() {
    const schemaDir = join(process.cwd(), 'prisma', 'schema');
    this.schemaContent = this.loadSchemaFiles(schemaDir);
  }

  private loadSchemaFiles(schemaDir: string): string {
    const files = readdirSync(schemaDir);
    let combinedContent = '';

    for (const file of files) {
      if (file.endsWith('.prisma')) {
        const filePath = join(schemaDir, file);
        combinedContent += readFileSync(filePath, 'utf-8') + '\n'; // Add a newline for separation
      }
    }

    return combinedContent;
  }

  parseModels(): EntityDefinition[] {
    const models: EntityDefinition[] = [];
    const modelRegex = /model\s+(\w+)\s*{([^}]+)}/g;
    let match;

    while ((match = modelRegex.exec(this.schemaContent)) !== null) {
      const modelName = match[1];
      const modelContent = match[2];
      
      const fields = this.parseFields(modelContent);

      const relationships = this.parseRelationships(modelContent, modelName);
      
      models.push({
        name: modelName,
        fields,
        relationships
      });
    }

    return models;
  }

  private parseFields(modelContent: string): FieldDefinition[] {
    const fields: FieldDefinition[] = [];
    const fieldRegex = /(\w+)\s+(\w+)(\?)?\s*(@[^@\n]+)?(?:\s*\/\/[^\n]*)?/g;
    let match;    

    while ((match = fieldRegex.exec(modelContent)) !== null) {
      const [fullMatch, name, type, isOptional, attributes] = match;
      // console.log('Field match:', { fullMatch, name, type, isOptional, attributes });
      
      // Skip relation fields as they're handled separately
      if (name.endsWith('Id')) {
        // console.log('Skipping relation field:', name);
        continue;
      }

      const fieldType = this.mapPrismaTypeToGraphQLType(type);
      if (!fieldType) {
        // console.log('Skipping field due to unmapped type:', { name, type });
        continue;
      }

      // Check if this is an auto-generated ID field
      const isAutoGeneratedId = attributes?.includes('@id') && attributes?.includes('@default(uuid())');

      fields.push({
        name,
        type: fieldType,
        isRequired: !isOptional || isAutoGeneratedId,
        isUnique: attributes?.includes('@unique') || false,
        defaultValue: isAutoGeneratedId ? 'uuid()' : this.parseDefaultValue(attributes)
      });
    }

    return fields;
  }

  private parseRelationships(modelContent: string, modelName: string): RelationshipDefinition[] {
    const relationships: RelationshipDefinition[] = [];
    
    // Match relation fields in the format: field_name model_name? @relation(...)
    const relationRegex = /(\w+)\s+(\w+)(\[\])?\s+@relation\([^)]+\)/g;
    let match;
    
    while ((match = relationRegex.exec(modelContent)) !== null) {
      const [_, field, target, isArray] = match;
      
      // Determine relationship type based on array notation
      const isOneToMany = !!isArray;
      
      relationships.push({
        type: isOneToMany ? 'one-to-many' : 'many-to-one',
        target,
        field,
        foreignKey: `${field}Id`
      });
    }

    // Also look for reverse relations in the format: model_name model_name[] @relation(...)
    const reverseRelationRegex = /(\w+)\s+(\w+)\[\](?:\s+@relation\([^)]+\))?/g;
    match = null;
    
    while ((match = reverseRelationRegex.exec(modelContent)) !== null) {
      const [_, field, target] = match;
      
      // This is a one-to-many relation from the current model's perspective
      relationships.push({
        type: 'one-to-many',
        target,
        field,
        foreignKey: `${field}Id`
      });
    }

    return relationships;
  }

  private mapPrismaTypeToGraphQLType(prismaType: string): 'string' | 'int' | 'float' | 'boolean' | 'id' | 'datetime' | null {
    switch (prismaType.toLowerCase()) {
      case 'string':
      case 'text':
      case 'varchar':
        return 'string';
      case 'int':
      case 'bigint':
      case 'integer':
        return 'int';
      case 'float':
      case 'decimal':
      case 'double':
      case 'real':
        return 'float';
      case 'boolean':
      case 'bool':
        return 'boolean';
      case 'datetime':
      case 'timestamp':
        return 'datetime';
      case 'uuid':
      case 'id':
        return 'id';
      default:        
        return null;
    }
  }

  private parseDefaultValue(attributes: string | undefined): any {
    if (!attributes) return undefined;
    
    const defaultValueMatch = attributes.match(/@default\(([^)]+)\)/);
    if (!defaultValueMatch) return undefined;

    const value = defaultValueMatch[1];
    if (value === 'true') return true;
    if (value === 'false') return false;
    if (!isNaN(Number(value))) return Number(value);
    return value.replace(/['"]/g, '');
  }
} 